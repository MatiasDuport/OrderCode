function resolveLanguage(language: AppLanguage): 'es' | 'en' {
  if (language === 'en' || language === 'es') return language;
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('en') ? 'en' : 'es';
}

export function translate(value: string, language: AppLanguage): string {
  if (resolveLanguage(language) !== 'en') return value;
  const trimmed = value.trim();
  const exact = english[trimmed];
  if (exact) return value.replace(trimmed, exact);
  const patterns: Array<[RegExp, string]> = [
    [/^OrderCode (.+) está disponible\.$/, 'OrderCode $1 is available.'], [/^OrderCode (.+) se descargó y verificó\. Puedes instalarlo cuando termines tu trabajo\.$/, 'OrderCode $1 has been downloaded and verified. You can install it when you finish your work.'],
    [/^(.+) · Gratis verificado · Conecta la clave API en Ajustes$/, '$1 · Verified free · Connect the API key in Settings'], [/^(.+) · Gratis verificado$/, '$1 · Verified free'], [/^(.+) · Plan ChatGPT · sujeto a límites$/, '$1 · ChatGPT plan · usage limits apply'], [/^(.+) · (\$[\d.]+ \/ \$[\d.]+) por 1M tokens$/, '$1 · $2 per 1M tokens'], [/^(.+) · Precio no verificado$/, '$1 · Pricing not verified'], [/^(.+) · Inferencia local · sin tarifa API$/, '$1 · Local inference · no API charge'], [/^(.+) · Conecta tu cuenta en Ajustes$/, '$1 · Connect your account in Settings'], [/^Conectado · (.+)$/, 'Connected · $1'],
    [/^Clave API (.+)$/, 'API key for $1'], [/^Eliminar (.+)$/, 'Remove $1'], [/^Desactivar (.+)$/, 'Disable $1'], [/^Activar (.+)$/, 'Enable $1'], [/^Editar (.+)$/, 'Edit $1'], [/^Exportar (.+)$/, 'Export $1'], [/^Cerrar terminal (.+)$/, 'Close terminal $1'], [/^Editor de código: (.+)$/, 'Code editor: $1'], [/^Grafo con (\d+) nodos y (\d+) relaciones$/, 'Graph with $1 nodes and $2 relationships'], [/^(\d+) archivo$/, '$1 file'], [/^(\d+) archivos$/, '$1 files'], [/^Versión (.+)$/, 'Version $1'], [/^(\d+) listos$/, '$1 ready'], [/^(\d+) proveedores disponibles$/, '$1 providers available'],
  ];
  for (const [pattern, replacement] of patterns) if (pattern.test(trimmed)) return value.replace(trimmed, trimmed.replace(pattern, replacement));
  return value;
}

const translatableProps = ['aria-label', 'title', 'placeholder', 'label', 'description'] as const;

function localizeNode(node: ReactNode, language: AppLanguage): ReactNode {
  if (typeof node === 'string') return translate(node, language);
  if (Array.isArray(node)) return Children.map(node, (child) => localizeNode(child, language));
  if (!isValidElement<Record<string, unknown>>(node)) return node;
  const props = { ...node.props };
  for (const key of translatableProps) if (typeof props[key] === 'string') props[key] = translate(props[key] as string, language);
  for (const [key, value] of Object.entries(props)) {
    if (key !== 'children' && (isValidElement(value) || Array.isArray(value))) props[key] = localizeNode(value as ReactNode, language);
  }
  if (props.children !== undefined) props.children = localizeNode(props.children as ReactNode, language);
  return cloneElement(node, props);
}

export function Localized({ children }: { children: ReactNode }) {
  const language = useDesktopStore((state) => state.language);
  return localizeNode(children, language);
}
